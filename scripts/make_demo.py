#!/usr/bin/env python3
"""Render docs/demo.gif from a fixed script.

The animation is synthetic: it is a transcript rendered frame by frame, not a
recording of a live session. The README labels it as such.

Usage: python scripts/make_demo.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 780, 430
BG = "#0d1117"
FG = "#c9d1d9"
ACCENT = "#58a6ff"
MUTED = "#8b949e"
USER = "#7ee787"
PAD = 28
LINE_H = 30

SCRIPT = [
    ("title", "socratic-elenchus"),
    ("blank", ""),
    ("user", "你   我觉得好内容就是有人看的内容。"),
    ("coach", "它   你的意思是：好 = 有人看。给我一个判断标准？"),
    ("user", "你   播放量高就是好。"),
    ("coach", "它   有没有一种情况，你会说它是好内容，但播放量很低？"),
    ("user", "你   ……有些讲得扎实的，播放量一般。"),
    ("coach", "它   所以「播放量低」和「好」可以同时成立。"),
    ("coach", "     这条定义，你改还是不改？"),
    ("blank", ""),
    ("footer", "一次一问 · 五个步骤 · 不下判决"),
]


def load_font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        Path("C:/Windows/Fonts/msyhbd.ttc" if bold else "C:/Windows/Fonts/msyh.ttc"),
        Path("C:/Windows/Fonts/msyh.ttc"),
    ]
    for path in candidates:
        if path.exists():
            return ImageFont.truetype(str(path), size)
    return ImageFont.load_default()


def wrap(text: str, font: ImageFont.FreeTypeFont, max_width: int) -> list[str]:
    if not text:
        return [""]
    lines, current = [], ""
    for char in text:
        if font.getlength(current + char) <= max_width:
            current += char
        else:
            lines.append(current)
            current = char
    if current:
        lines.append(current)
    return lines


def render(visible: int, cursor: bool) -> Image.Image:
    image = Image.new("RGB", (WIDTH, HEIGHT), BG)
    draw = ImageDraw.Draw(image)

    body = load_font(20)
    title = load_font(22, bold=True)
    small = load_font(15)

    y = PAD
    for kind, text in SCRIPT[:visible]:
        if kind == "blank":
            y += LINE_H // 2
            continue
        font = title if kind == "title" else body
        color = {"title": ACCENT, "user": USER, "coach": FG, "footer": MUTED}[kind]
        for chunk in wrap(text, font, WIDTH - 2 * PAD):
            draw.text((PAD, y), chunk, font=font, fill=color)
            y += LINE_H

    if cursor:
        draw.rectangle([PAD, y + 4, PAD + 10, y + 24], fill=ACCENT)

    if visible >= len(SCRIPT):
        draw.text((PAD, HEIGHT - 34), "synthetic demo · generated by scripts/make_demo.py",
                  font=small, fill=MUTED)
    return image


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "docs" / "demo.gif"
    frames, durations = [], []
    for visible in range(2, len(SCRIPT) + 1):
        frames.append(render(visible, cursor=True).quantize(colors=48))
        durations.append(320)
    frames.append(render(len(SCRIPT), cursor=False).quantize(colors=48))
    durations.append(2600)

    out.parent.mkdir(parents=True, exist_ok=True)
    frames[0].save(
        out,
        save_all=True,
        append_images=frames[1:],
        duration=durations,
        loop=0,
        optimize=True,
        disposal=2,
    )
    print(f"wrote {out} ({out.stat().st_size / 1024:.1f} KB, {len(frames)} frames)")


if __name__ == "__main__":
    main()
